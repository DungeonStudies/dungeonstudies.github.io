"""Build index-test.html from index.html.

A test build is the same game with two differences, and the second one is the
important one:

  1. It has a cheat panel - instant kill, jump to any floor, god mode, force an
     omen or a nemesis, hand yourself levels and gold.
  2. It cannot touch the real save. Every storage key is prefixed, so the test
     build reads and writes its own profiles and its own Index. Play it for an
     hour, delete it, and the real run is exactly where you left it.

Run it again after any change to index.html:  python3 tools/maketest.py
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'index.html'
OUT = ROOT / 'index-test.html'

html = SRC.read_text(encoding='utf-8')

# ---------------------------------------------------------------- 1. the save
# Both storage paths get the prefix: the localStorage fallback and the host
# store. Miss either one and the test build starts eating the real profiles.
subs = [
    ("localStorage.getItem('sd_'+key)", "localStorage.getItem('sdtest_'+key)"),
    ("localStorage.setItem('sd_'+key,", "localStorage.setItem('sdtest_'+key,"),
    ("await window.storage.get(key)", "await window.storage.get('sdtest_'+key)"),
    ("await window.storage.set(key, value)", "await window.storage.set('sdtest_'+key, value)"),
]
for old, new in subs:
    if old not in html:
        sys.exit('maketest: could not find %r - index.html has moved on, '
                 'fix tools/maketest.py before shipping a test build' % old[:48])
    html = html.replace(old, new, 1)

# a title you cannot mistake for the real thing
html, n = re.subn(r'<title>(.*?)</title>', r'<title>⚑ TEST BUILD — \1</title>', html, count=1)
if not n:
    sys.exit('maketest: no <title> to mark')

